# 📝 დავალება 1
nums = [10, 20, 30, 40]
nums.append(50)           # ვამატებთ 50 სიაში
nums.insert(1, 15)        # ჩავსვამთ 15 ინდექსზე 1-ზე
print("დავალება 1:", nums)
# შედეგი: [10, 15, 20, 30, 40, 50]


# 📝 დავალება 2
fruits = ["ვაშლი", "მსხალი", "ბალი", "ატამი", "მსხალი"]
index_value = fruits.index("მსხალი")     # ვპოულობთ პირველ ინდექსს
count_value = fruits.count("მსხალი")     # ვითვლით რამდენჯერ გვხვდება
print("დავალება 2: პირველი ინდექსი =", index_value)
print("დავალება 2: რაოდენობა =", count_value)
# შედეგი: პირველი ინდექსი = 1, რაოდენობა = 2


# 📝 დავალება 3
letters = ["კ", "ბ", "ა", "გ", "დ"]
letters.sort()        # ალაგებს ანბანის მიხედვით
letters.remove("გ")   # შლის "გ"
print("დავალება 3:", letters)
# შედეგი: ['ა', 'ბ', 'დ', 'კ']


# 📝 დავალება 4
text = "python is fun"
