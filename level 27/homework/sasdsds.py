# 1) print-ის და return-ის დადებითი და უარყოფითი მხარეები:

# print():
# ✅ დადებითი:
# - გამოსაყენებელია, როცა გვსურს შედეგის დანახვა ტერმინალში (დამწყებთათვის მოსახერხებელია).
# ❌ უარყოფითი:
# - ვერ ვიყენებთ შედეგს პროგრამის სხვა ნაწილებში, რადგან print() მხოლოდ ბეჭდავს მნიშვნელობას და არ აბრუნებს მას.

# return:
# ✅ დადებითი:
# - აბრუნებს მნიშვნელობას, რომლის გამოყენებაც შესაძლებელია პროგრამის სხვა ადგილებში (მაგ. სხვა ფუნქციაში ან გამოთვლაში).
# ❌ უარყოფითი:
# - არ ბეჭდავს შედეგს ტერმინალში, ამიტომ შედეგის დასანახად საჭიროა print(function_name()) გამოყენება.


# 2) check_age ფუნქცია
def check_age(age):
    if age >= 18:
        print("Access Granted")
    else:
        print("Access Denied")


# 3) user_info ფუნქცია
def user_info(name, surname, address):
    return f"მომხმარებლის სახელი: {name}\nმომხმარებლის გვარი: {surname}\nმომხმარებლის მისამართი: {address}"


# 4) ფუნქცია, რომელიც აბრუნებს num1 აყვანილს num2-ის ხარისხში
def power(num1, num2):
    return num1 ** num2


# 5) ფუნქცია, რომელიც აბრუნებს რიცხვების საშუალო არითმეტიკულს
def arithmetic_average(numbers):
    return sum(numbers) / len(numbers)


# 🌟 ტესტი (შეგიძლია გაამოწმო როგორ მუშაობს)
check_age(20)  # გამოიტანს: Access Granted
check_age(15)  # გამოიტანს: Access Denied

print(user_info("ნიკა", "კეშელავა", "თბილისი"))
# გამოიტანს:
# მომხმარებლის სახელი: ნიკა
# მომხმარებლის გვარი: კეშელავა
# მომხმარებლის მისამართი: თბილისი

print(power(2, 3))  # 8
print(arithmetic_average([2, 4, 6, 8]))  # 5.0
